const C = (name, desc, opts, perm, run, flags = {}) => ({ name, desc, opts, perm, run, ...flags });
const U = (req = true, n = 'user', d = 'Target member') => ({ n, d, t: 'user', req });
const S = (n, d, req = true, x = {}) => ({ n, d, t: 'str', req, ...x });
const I = (n, d, req = true, min, max) => ({ n, d, t: 'int', req, min, max });
const B = (n, d, req = false) => ({ n, d, t: 'bool', req });
const CH = (n, d, req = false, types) => ({ n, d, t: 'chan', req, types });
const R = (n, d, req = true) => ({ n, d, t: 'role', req });
const RS = () => S('reason', 'Reason (saved in logs)', false, { max: 300 });
const DUR = (req = true, n = 'duration', d = 'e.g. 10m, 2h, 1d') => S(n, d, req, { max: 30 });
module.exports = { C, U, S, I, B, CH, R, RS, DUR };
